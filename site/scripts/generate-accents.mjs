/**
 * Writes src/styles/product-accents.css from the `accent` / `accentAlt` fields of every product
 * in src/content/products/*.md. Runs automatically before `dev` and `build`.
 *
 * Why generated CSS: the Content-Security-Policy forbids inline style attributes, so per-product
 * colours cannot be injected at runtime. Products are styled through [data-accent="<slug>"].
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = `${root}src/content/products`;
const HEX = /^#[0-9a-fA-F]{6}$/;

export function buildAccentCss(products) {
  const rules = products
    .filter((p) => p.accent && HEX.test(p.accent) && /^[a-z0-9-]+$/.test(p.slug))
    .sort((a, b) => a.slug.localeCompare(b.slug))
    .map((p) => {
      const alt = p.accentAlt && HEX.test(p.accentAlt) ? p.accentAlt : p.accent;
      return `[data-accent='${p.slug}'] {\n  --accent: ${p.accent.toLowerCase()};\n  --accent-alt: ${alt.toLowerCase()};\n}`;
    });
  return `/* GENERATED by scripts/generate-accents.mjs from src/content/products — do not edit. */\n${rules.join('\n')}\n`;
}

export function readProducts() {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md') && !f.startsWith('_'))
    .map((f) => parse(/^---\n([\s\S]*?)\n---/.exec(readFileSync(`${dir}/${f}`, 'utf8'))?.[1] ?? '') ?? {});
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(`${root}src/styles/product-accents.css`, buildAccentCss(readProducts()));
  console.log('product-accents.css written');
}
